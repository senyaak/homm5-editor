/**
 * Where a box's message text was written, so the block can point at it.
 *
 * The behaviour shows a text REF, not a string — `MessageBox` takes a file —
 * so a box whose author typed a message needs that message written somewhere
 * first. Whoever generates the block (the editor's save, a test) writes the
 * files and answers this; a box with a message and no answer is refused rather
 * than quietly silenced.
 */
export type MessageRef = (box: PandoraContents) => string | undefined;

/**
 * Where the author's message was written, as the writer of the map answers.
 *
 * ONE TEXT, because one is all a box has to say. A receipt of what it handed
 * over used to ride beside it and is gone: the game announces its own gains —
 * experience, gold, resources, an artifact — and a line of ours under each is
 * noise. The two it stays silent about get the ENGINE's announcement instead
 * (native/qol/pandora-notify.c), not a caption written here.
 */
export interface PandoraRefs {
  said?: MessageRef;
  /**
   * The talisman ladder, in the game's own order — `talismanLadder()` in
   * pandora-prices.ts, which reads it off `DefaultStats.xdb`.
   *
   * What it decides is which of a box's spells are ADVENTURE magic, and those
   * are written into a list of their own: a barbarian cannot be taught one and
   * takes a step up this ladder instead. Left out (a test with no data root,
   * an install missing the table) every spell goes down the teaching path,
   * which is what a box did before any of this existed.
   */
  ladder?: readonly string[];
}

